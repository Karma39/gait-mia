"""
Read NB06d npz artifacts and write per-N ASR LaTeX macros for all datasets.
Run with: python scripts/write_06d_asr_macros.py

Cross-pool (MN, NM) macros default to \pholder until the _cross.npz files exist.
Re-run after NB06d completes on the cluster to fill in real values.
"""
import numpy as np
from pathlib import Path

ARTIFACT_BASE = Path(__file__).parent.parent / 'artifacts'
LATEX_OUT     = Path(__file__).parent.parent / 'latex' / 'generated' / 'nb06d_asr_table_macros.tex'

N_GRID    = [1, 2, 4, 8, 16, 32, 64, 128]
N_NAMES   = {1: 'One', 2: 'Two', 4: 'Four', 8: 'Eight',
             16: 'Sixteen', 32: 'ThirtyTwo', 64: 'SixtyFour', 128: 'OneTwentyEight'}
DATASETS  = ['whuGAIT', 'ucihar', 'wisdm']
PREFIX    = {'whuGAIT': 'whuGAIT', 'ucihar': 'ucihar', 'wisdm': 'wisdm'}

lines = ['% Auto-generated by scripts/write_06d_asr_macros.py — DO NOT EDIT MANUALLY',
         '% Re-run after NB06d completes to replace \\pholder entries with real values.',
         r'\providecommand{\pholder}{\textbf{??}}',
         '']

for ds in DATASETS:
    prefix = PREFIX[ds]
    art = ARTIFACT_BASE / ds

    d_full    = np.load(art / f'06d_{ds}_ksearch_full.npz')
    d_quarter = np.load(art / f'06d_{ds}_ksearch_quarter.npz')

    # Try to load cross-pool results (may not exist yet)
    cross_full_path    = art / f'06d_{ds}_ksearch_full_cross.npz'
    cross_quarter_path = art / f'06d_{ds}_ksearch_quarter_cross.npz'
    d_full_cross    = np.load(cross_full_path)    if cross_full_path.exists()    else None
    d_quarter_cross = np.load(cross_quarter_path) if cross_quarter_path.exists() else None

    lines.append(f'% ── {ds} ──')
    for N in N_GRID:
        n_word = N_NAMES[N]

        for cond, d_mm_nn, d_cross in [
            ('Full',    d_full,    d_full_cross),
            ('Quarter', d_quarter, d_quarter_cross),
        ]:
            asr_te = float((d_mm_nn['n_min_te'] <= N).mean())
            asr_tr = float((d_mm_nn['n_min_tr'] <= N).mean())

            # NN and MM — always available
            lines += [
                f'\\providecommand{{\\ksASRTe{cond}N{n_word}{prefix}}}{{}}',
                f'\\renewcommand{{\\ksASRTe{cond}N{n_word}{prefix}}}{{{asr_te:.3f}}}',
                f'\\providecommand{{\\ksASRTr{cond}N{n_word}{prefix}}}{{}}',
                f'\\renewcommand{{\\ksASRTr{cond}N{n_word}{prefix}}}{{{asr_tr:.3f}}}',
            ]

            # MN and NM — available only after cross-pool run
            if d_cross is not None:
                asr_mn = float((d_cross['n_min_mn'] <= N).mean())
                asr_nm = float((d_cross['n_min_nm'] <= N).mean())
                lines += [
                    f'\\providecommand{{\\ksASRMn{cond}N{n_word}{prefix}}}{{\\pholder}}',
                    f'\\renewcommand{{\\ksASRMn{cond}N{n_word}{prefix}}}{{{asr_mn:.3f}}}',
                    f'\\providecommand{{\\ksASRNm{cond}N{n_word}{prefix}}}{{\\pholder}}',
                    f'\\renewcommand{{\\ksASRNm{cond}N{n_word}{prefix}}}{{{asr_nm:.3f}}}',
                ]
            else:
                lines += [
                    f'\\providecommand{{\\ksASRMn{cond}N{n_word}{prefix}}}{{\\pholder}}',
                    f'\\providecommand{{\\ksASRNm{cond}N{n_word}{prefix}}}{{\\pholder}}',
                ]

    lines.append('')

LATEX_OUT.write_text('\n'.join(lines) + '\n')
print(f'Written {LATEX_OUT}')
for ds in DATASETS:
    art = ARTIFACT_BASE / ds
    cross_exists = (art / f'06d_{ds}_ksearch_full_cross.npz').exists()
    print(f'  {ds}: cross-pool {"AVAILABLE" if cross_exists else "pending (\\pholder)"}')
