"""Regenerate compare_mia_*_metrics.tex macro files from stored artifacts.

Reproduces the LiRA warm/cold computations from NB05c using the Sep-27
shadow artifacts and the 05a_target_deltas.npz target scores.

Run from the gait_mia/ directory:
    python scripts/regenerate_compare_mia_macros.py
"""
import json
import sys
from datetime import datetime
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent.parent))
from src.attacks.lira_shadow import lira_eval

ARTIFACT_DIR = Path("artifacts")
GENERATED_DIR = Path("latex/generated")
DATASETS = ["whuGAIT", "ucihar", "wisdm", "combined"]

# ── Macro-file header ─────────────────────────────────────────────────────────
def make_header(ds):
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    return (
        f"% Auto-generated by scripts/regenerate_compare_mia_macros.py\n"
        f"% Last run: {ts}\n\n"
    )

def macro_pair(name, auc, tpr):
    """Return providecommand + renewcommand lines for AUC and TPR@10%."""
    auc_s = f"{auc:.3f}"
    tpr_s = f"{tpr:.3f}"
    lines = []
    for suffix, val in [("AUC", auc_s), ("TPRten", tpr_s)]:
        lines.append(f"\\providecommand{{\\{name}{suffix}}}{{}}")
        lines.append(f"\\renewcommand{{\\{name}{suffix}}}{{{val}}}")
    return "\n".join(lines)

# ── Per-dataset computation ───────────────────────────────────────────────────
for ds in DATASETS:
    print(f"\n{'='*60}")
    print(f"Dataset: {ds}")

    # Target scores (written by NB05a, same as NB05c cell 4)
    td = np.load(ARTIFACT_DIR / ds / "05a_target_deltas.npz")
    m_ids  = td["member_ids"].tolist()
    nm_ids = td["nonmember_ids"].tolist()

    tgt_raw = {
        **dict(zip(m_ids,  td["member_raw"].tolist())),
        **dict(zip(nm_ids, td["nonmember_raw"].tolist())),
    }
    tgt_lf = {
        **dict(zip(m_ids,  td["member_lf"].tolist())),
        **dict(zip(nm_ids, td["nonmember_lf"].tolist())),
    }
    tgt_mf = {
        **dict(zip(m_ids,  td["member_mf"].tolist())),
        **dict(zip(nm_ids, td["nonmember_mf"].tolist())),
    }

    # Shadow artifacts (written by NB05c on Sep 27)
    warm_r = json.load(open(ARTIFACT_DIR / ds / f"05c_lira_warm_shadows_{ds}.json"))
    cold_r = json.load(open(ARTIFACT_DIR / ds / f"05c_lira_cold_shadows_{ds}.json"))

    def int_keys(d):
        return {int(k): v for k, v in d.items()}

    w_raw = int_keys(warm_r["raw"])
    w_lf  = int_keys(warm_r["lf"])
    w_mf  = int_keys(warm_r["mf"])
    c_raw = int_keys(cold_r["raw"])
    c_lf  = int_keys(cold_r["lf"])
    c_mf  = int_keys(cold_r["mf"])

    # Grey values come from per_subject_report (written by NB05b)
    grey_r = json.load(open(ARTIFACT_DIR / ds / "05b_per_subject_report.json"))
    ps = grey_r["per_subject"]
    member_set = {s["subject_id"] for s in ps if s["true_label"] == "member"}

    def grey_auc_tpr(score_key):
        scores = [s[score_key]["score"] for s in ps]
        labels = [1 if s["subject_id"] in member_set else 0 for s in ps]
        from sklearn.metrics import roc_curve, auc as sk_auc
        fpr, tpr, _ = roc_curve(labels, scores)
        auc_v = sk_auc(fpr, tpr)
        # tpr_at_fpr
        idx = np.searchsorted(fpr, 0.10, side="right") - 1
        tpr10 = float(tpr[max(idx, 0)])
        return auc_v, tpr10

    g_raw_auc, g_raw_tpr = grey_auc_tpr("LiRA-raw")
    g_lf_auc,  g_lf_tpr  = grey_auc_tpr("LiRA-lf")
    g_mf_auc,  g_mf_tpr  = grey_auc_tpr("LiRA-mf")

    # lira_eval calls (exact same function as NB05c)
    _, _, w_raw_auc, w_raw_tpr, *_ = lira_eval(w_raw, tgt_raw, m_ids, nm_ids)
    _, _, w_lf_auc,  w_lf_tpr,  *_ = lira_eval(w_lf,  tgt_lf,  m_ids, nm_ids)
    _, _, w_mf_auc,  w_mf_tpr,  *_ = lira_eval(w_mf,  tgt_mf,  m_ids, nm_ids)
    _, _, c_raw_auc, c_raw_tpr, *_ = lira_eval(c_raw, tgt_raw, m_ids, nm_ids)
    _, _, c_lf_auc,  c_lf_tpr,  *_ = lira_eval(c_lf,  tgt_lf,  m_ids, nm_ids)
    _, _, c_mf_auc,  c_mf_tpr,  *_ = lira_eval(c_mf,  tgt_mf,  m_ids, nm_ids)

    print(f"  grey  raw AUC={g_raw_auc:.4f}  TPR={g_raw_tpr:.4f}")
    print(f"  warm  raw AUC={w_raw_auc:.4f}  TPR={w_raw_tpr:.4f}")
    print(f"  warm  lf  AUC={w_lf_auc:.4f}  TPR={w_lf_tpr:.4f}")
    print(f"  warm  mf  AUC={w_mf_auc:.4f}  TPR={w_mf_tpr:.4f}")
    print(f"  cold  raw AUC={c_raw_auc:.4f}  TPR={c_raw_tpr:.4f}")
    print(f"  cold  lf  AUC={c_lf_auc:.4f}  TPR={c_lf_tpr:.4f}")
    print(f"  cold  mf  AUC={c_mf_auc:.4f}  TPR={c_mf_tpr:.4f}")

    # ── Read the existing macro file to preserve grey/simpld/etc. lines ─────
    ds_tag = {"whuGAIT": "whuGAIT", "ucihar": "ucihar", "wisdm": "wisdm", "combined": "combined"}[ds]
    macro_path = GENERATED_DIR / f"compare_mia_{ds_tag}_metrics.tex"
    existing = macro_path.read_text()

    # ── Patch only the warm/cold lines we own ──────────────────────────────
    import re

    def patch(text, macro_name, new_val):
        pattern = r"(\\renewcommand\{\\%s\})\{[^}]*\}" % re.escape(macro_name)
        return re.sub(pattern, r"\g<1>{%s}" % new_val, text)

    def fmt(v):
        return f"{v:.3f}"

    cap = ds_tag[0].upper() + ds_tag[1:]  # capitalise first letter for macro prefix
    # actual macro prefixes:
    pfx = {"whuGAIT": "whuGAIT", "ucihar": "ucihar", "wisdm": "wisdm", "combined": "combined"}[ds]

    patches = {
        f"{pfx}GreyLiraRawAUC":    fmt(g_raw_auc),
        f"{pfx}GreyLiraRawTPRten": fmt(g_raw_tpr),
        f"{pfx}GreyLiraLfAUC":     fmt(g_lf_auc),
        f"{pfx}GreyLiraLfTPRten":  fmt(g_lf_tpr),
        f"{pfx}GreyLiraMfAUC":     fmt(g_mf_auc),
        f"{pfx}GreyLiraMfTPRten":  fmt(g_mf_tpr),
        f"{pfx}WarmLiraRawAUC":    fmt(w_raw_auc),
        f"{pfx}WarmLiraRawTPRten": fmt(w_raw_tpr),
        f"{pfx}WarmLiraLfAUC":     fmt(w_lf_auc),
        f"{pfx}WarmLiraLfTPRten":  fmt(w_lf_tpr),
        f"{pfx}WarmLiraMfAUC":     fmt(w_mf_auc),
        f"{pfx}WarmLiraMfTPRten":  fmt(w_mf_tpr),
        f"{pfx}ColdLiraRawAUC":    fmt(c_raw_auc),
        f"{pfx}ColdLiraRawTPRten": fmt(c_raw_tpr),
        f"{pfx}ColdLiraLfAUC":     fmt(c_lf_auc),
        f"{pfx}ColdLiraLfTPRten":  fmt(c_lf_tpr),
        f"{pfx}ColdLiraMfAUC":     fmt(c_mf_auc),
        f"{pfx}ColdLiraMfTPRten":  fmt(c_mf_tpr),
    }

    updated = existing
    # Patch timestamp comment
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    updated = re.sub(
        r"% Last run:.*",
        f"% Last run: {ts} (regenerated by scripts/regenerate_compare_mia_macros.py)",
        updated,
    )
    # Patch existing macros; collect any that are missing and append them
    missing_appends = []
    for macro_name, new_val in patches.items():
        if f"\\{macro_name}" in updated:
            updated = patch(updated, macro_name, new_val)
        else:
            missing_appends.append(
                f"\\providecommand{{\\{macro_name}}}{{}}\n"
                f"\\renewcommand{{\\{macro_name}}}{{{new_val}}}"
            )
    if missing_appends:
        updated = updated.rstrip() + "\n" + "\n".join(missing_appends) + "\n"

    macro_path.write_text(updated)
    print(f"  Written: {macro_path}")

print("\nDone.")
